"""Evaluation: LM bits-per-byte, controlled-task accuracy, generation quality, diffusion denoising, run reports."""
import argparse
import json
import math
import os
import time

import torch
import torch.nn.functional as F

import data

LN2 = math.log(2)
BUCKETS = ((0, 16), (16, 64), (64, 256), (256, None))


def seq_len_of(model):
    return model.lm.seq_len if hasattr(model, "lm") else model.cfg.model.seq_len


def _sync(device):
    if str(device).startswith("cuda"):
        torch.cuda.synchronize()


def _windows(blob, size, stride, count=None):
    n = max(0, (len(blob) - size) // stride + 1)
    if count is not None:
        n = min(n, count)
    return torch.stack([blob[i * stride:i * stride + size] for i in range(n)]) if n else blob.new_zeros((0, size))


@torch.no_grad()
def eval_lm(model, data_name, split="val", device="cpu", max_windows=None, batch_size=32):
    model.to(device).eval()
    L = seq_len_of(model)
    w = _windows(data.load_split(data_name, split), L + 1, L + 1, max_windows)
    if len(w) == 0:
        raise ValueError(f"{data_name}/{split} has fewer than {L + 1} bytes")
    sums = torch.zeros(L, dtype=torch.float64)
    for i in range(0, len(w), batch_size):
        b = w[i:i + batch_size].to(device).long()
        with torch.autocast(device_type=torch.device(device).type, enabled=False):
            lg = model.logits(b[:, :-1]).float()
        ce = F.cross_entropy(lg.reshape(-1, lg.size(-1)), b[:, 1:].reshape(-1), reduction="none").view(b.size(0), L)
        sums += ce.sum(0).double().cpu()
    n = len(w)
    out = {"bpb": sums.sum().item() / (n * L) / LN2, "windows": n, "bytes": n * L, "seq_len": L, "bpb_by_context": {}}
    for lo, hi in BUCKETS:
        hi_c = min(hi, L) if hi else L
        if lo < hi_c:
            out["bpb_by_context"][f"{lo}-{hi or 'inf'}"] = sums[lo:hi_c].sum().item() / (n * (hi_c - lo)) / LN2
    return out


@torch.no_grad()
def eval_tasks(model, data_name, device="cpu", batch_size=64):
    try:
        tasks = data.load_eval_tasks(data_name)
    except FileNotFoundError:
        return {}
    model.to(device).eval()
    L = seq_len_of(model) + 1
    out = {}
    for task, regimes in tasks.items():
        out[task] = {}
        for regime, items in regimes.items():
            tok_ok = tok_n = ex_ok = 0
            for i in range(0, len(items), batch_size):
                chunk = [(b[:L], m[:L]) for b, m in items[i:i + batch_size]]
                width = max(len(b) for b, _ in chunk)
                x = torch.zeros(len(chunk), width, dtype=torch.long)  # causal: right padding cannot affect earlier positions
                for r, (b, _) in enumerate(chunk):
                    x[r, :len(b)] = torch.tensor(list(b))
                pred = model.logits(x[:, :-1].to(device)).argmax(-1).cpu()  # pred[:, j] predicts byte j+1
                for r, (b, m) in enumerate(chunk):
                    pos = [j for j in range(1, len(b)) if m[j]]
                    ok = [bool(pred[r, j - 1] == x[r, j]) for j in pos]
                    tok_ok += sum(ok)
                    tok_n += len(ok)
                    ex_ok += bool(ok) and all(ok)
            out[task][regime] = {"token_acc": tok_ok / max(tok_n, 1), "exact_match": ex_ok / max(len(items), 1), "examples": len(items)}
    return out


# --- text metrics over generated byte strings ---

def valid_utf8(b):
    try:
        bytes(b).decode("utf-8")
        return True
    except UnicodeDecodeError:
        return False


def printable_fraction(b):
    return sum(32 <= c < 127 or c in (9, 10, 13) for c in b) / len(b) if len(b) else 0.0


def ngrams(b, n):
    b = bytes(b)
    return [b[i:i + n] for i in range(len(b) - n + 1)]


def distinct_ngram_ratio(b, n=4):
    g = ngrams(b, n)
    return len(set(g)) / len(g) if g else None


def repeated_ngram_fraction(b, n=8):
    """Fraction of n-gram positions whose n-gram already occurred earlier in the same string."""
    g, seen, rep = ngrams(b, n), set(), 0
    for x in g:
        rep += x in seen
        seen.add(x)
    return rep / len(g) if g else None


def memorization_rate(samples, train_bytes, win=32, stride=16, cap=2000):
    ws = [bytes(s[i:i + win]) for s in samples for i in range(0, len(s) - win + 1, stride)][:cap]
    return sum(w in train_bytes for w in ws) / len(ws) if ws else 0.0


def _mean(xs):
    xs = [x for x in xs if x is not None]
    return sum(xs) / len(xs) if xs else 0.0


def text_metrics(samples, train_bytes=None):
    out = {"valid_utf8_rate": _mean([float(valid_utf8(s)) for s in samples]),
           "printable_rate": _mean([printable_fraction(s) for s in samples]),
           "distinct_4gram_ratio": _mean([distinct_ngram_ratio(s, 4) for s in samples]),
           "repeated_8gram_fraction": _mean([repeated_ngram_fraction(s, 8) for s in samples])}
    if train_bytes is not None:
        out["memorization_rate"] = memorization_rate(samples, train_bytes)
    return out


def eval_generation(model, data_name, device="cpu", n=8, new_bytes=200, seeds=(0, 1, 2, 3), temperature=0.8, top_k=40,
                    prompt_len=32, split="val"):
    model.to(device).eval()
    train_bytes = data.load_split(data_name, "train").numpy().tobytes()
    gen, elapsed, gen_bytes, conts, shown = hasattr(model, "generate"), 0.0, 0, [], []
    if gen:
        val = data.load_split(data_name, split)
        starts = [i * (len(val) - prompt_len) // max(n, 1) for i in range(n)]
        prompts = torch.stack([val[s:s + prompt_len] for s in starts]).long().to(device)
        g = torch.Generator(device=device)
        model.generate(prompts[:1], 2, temperature, top_k, g.manual_seed(0))  # warm-up
    else:
        model.sample(1)
    for seed in seeds:
        _sync(device)
        t0 = time.perf_counter()
        if gen:
            ids = model.generate(prompts, new_bytes, temperature, top_k, g.manual_seed(seed))
        else:
            torch.manual_seed(seed)
            ids = model.sample(n)
        _sync(device)
        elapsed += time.perf_counter() - t0
        ids = ids.cpu().to(torch.uint8)
        for r in range(ids.size(0)):
            row = ids[r].tolist()
            cont = row[prompt_len:] if gen else row
            conts.append(bytes(cont))
            gen_bytes += len(cont)
            if seed == seeds[0] and len(shown) < n:
                shown.append({"prompt": bytes(row[:prompt_len]).decode("utf-8", "replace") if gen else "",
                              "text": bytes(cont).decode("utf-8", "replace"), "repr": ascii(bytes(cont))})
    out = {"samples": shown, "n_generated": len(conts), "temperature": temperature, "top_k": top_k, **text_metrics(conts, train_bytes)}
    out["latency"] = {"bytes_per_s": gen_bytes / elapsed} if gen else {"seconds_per_sample": elapsed / max(len(conts), 1)}
    return out


@torch.no_grad()
def eval_diffusion(model, data_name, split="val", device="cpu", num_buckets=4, windows=64, batch_size=16, seed=1234):
    model.to(device).eval()
    gd, L = model.gaussian_diffusion, model.cfg.model.seq_len
    T = gd.num_timesteps
    x = _windows(data.load_split(data_name, split), L, L, windows).long()
    W = len(x)
    if W == 0:
        raise ValueError(f"{data_name}/{split} has fewer than {L} bytes")
    gen = torch.Generator().manual_seed(seed)
    emb_dim = model.cfg.model.byte_embed_dim
    buckets = []
    for b in range(num_buckets):
        lo, hi = b * T // num_buckets, (b + 1) * T // num_buckets
        t_all = torch.tensor([min(hi - 1, lo + int((j + 0.5) * (hi - lo) / W)) for j in range(W)])
        noise_all = torch.randn(W, L, emb_dim, generator=gen)
        nl, ce, acc = [], [], []
        for i in range(0, W, batch_size):
            xb, t, noise = x[i:i + batch_size].to(device), t_all[i:i + batch_size].to(device), noise_all[i:i + batch_size].to(device)
            x0 = model.byte_embedder(xb)
            xt = gd.q_sample(x0, t, noise=noise)
            table = model.embedding_table()
            if gd.self_cond:  # two-pass, as in training (first pass zeros -> x0_prev -> second pass)
                e0 = gd.denoise(xt, t)
                pred = gd.denoise(xt, t, x0_prev=gd.x0_estimate(xt, t, e0, x0.norm(dim=-1).mean(), table=table))
            else:
                pred = gd.denoise(xt, t)
            if gd.param == "logits":  # network output = byte logits; noise_loss reported for the implied eps; x0 acc = argmax(logits) acc
                lg = pred.float()
                d = noise - gd.eps_from_x0(xt, t, gd.x0_from_logits(lg, table))
            else:
                d = noise - pred
                lg = model.get_logits(gd.predict_start_from_noise(xt, t, pred))
            nl.append((d.abs() if gd.loss_type == "l1" and gd.param != "logits" else d.pow(2)).mean(dim=(1, 2)).cpu())
            ce.append(F.cross_entropy(lg.reshape(-1, lg.size(-1)), xb.reshape(-1), reduction="none").view(xb.shape).mean(1).cpu())
            acc.append((lg.argmax(-1) == xb).float().mean(1).cpu())
        nl, ce, acc = torch.cat(nl), torch.cat(ce), torch.cat(acc)
        buckets.append({"t_range": [lo, hi], "noise_loss": nl.mean().item(), "ce_loss": ce.mean().item(), "x0_acc": acc.mean().item()})
    mean = lambda k: sum(b[k] for b in buckets) / len(buckets)
    return {"noise_loss": mean("noise_loss"), "ce_loss": mean("ce_loss"), "x0_acc": mean("x0_acc"), "windows": W, "buckets": buckets}


# --- run reports ---

def _read_jsonl(path):
    rows = []
    if os.path.exists(path):
        with open(path) as f:
            for line in f:
                try:
                    rows.append(json.loads(line))
                except json.JSONDecodeError:
                    pass
    return rows


def training_stats(run_dir, model=None):
    rows = _read_jsonl(os.path.join(run_dir, "metrics.jsonl"))
    last = ([r for r in rows if not r.get("eval")] or [{}])[-1]
    elapsed, seen = last.get("elapsed"), last.get("bytes_seen")
    meta = {}
    if os.path.exists(os.path.join(run_dir, "meta.json")):
        with open(os.path.join(run_dir, "meta.json")) as f:
            meta = json.load(f)
    params = meta.get("params") or meta.get("param_count") or (sum(p.numel() for p in model.parameters()) if model is not None else None)
    peaks = [r["peak_vram_mb"] for r in rows if r.get("peak_vram_mb") is not None]
    return {"last_update": last.get("update"), "bytes_seen": seen, "examples": last.get("examples"), "elapsed_s": elapsed,
            "bytes_per_s": seen / elapsed if seen and elapsed else None,
            "examples_per_s": last["examples"] / elapsed if last.get("examples") and elapsed else None,
            "peak_vram_mb": max(peaks) if peaks else None, "params": params, "last_train_loss": last.get("loss")}


def _fmt(v):
    return "-" if v is None else (f"{v:.4g}" if isinstance(v, float) else str(v))


def to_markdown(rep):
    L = [f"## {rep['run']} ({rep['arch']}, {rep['which']}, {rep['split']} on {rep['data']})", ""]
    L += ["| training stat | value |", "|---|---|"] + [f"| {k} | {_fmt(v)} |" for k, v in rep["training"].items()]
    if "lm" in rep:
        lm = rep["lm"]
        L += ["", f"**bpb {lm['bpb']:.4f}** ({lm['windows']} windows, seq_len {lm['seq_len']})", "",
              "| context pos | bpb |", "|---|---|"] + [f"| {k} | {v:.4f} |" for k, v in lm["bpb_by_context"].items()]
    if rep.get("tasks"):
        L += ["", "| task | regime | token acc | exact match | n |", "|---|---|---|---|---|"]
        L += [f"| {t} | {r} | {v['token_acc']:.3f} | {v['exact_match']:.3f} | {v['examples']} |" for t, rs in rep["tasks"].items() for r, v in rs.items()]
    if "diffusion" in rep:
        d = rep["diffusion"]
        L += ["", f"noise_loss {d['noise_loss']:.4f}, ce_loss {d['ce_loss']:.4f}, x0_acc {d['x0_acc']:.3f}", "",
              "| t range | noise loss | ce loss | x0 acc |", "|---|---|---|---|"]
        L += [f"| {b['t_range'][0]}-{b['t_range'][1]} | {b['noise_loss']:.4f} | {b['ce_loss']:.4f} | {b['x0_acc']:.3f} |" for b in d["buckets"]]
    if "generation" in rep:
        g = rep["generation"]
        L += ["", "| generation metric | value |", "|---|---|"]
        L += [f"| {k} | {_fmt(g[k])} |" for k in ("valid_utf8_rate", "printable_rate", "distinct_4gram_ratio", "repeated_8gram_fraction", "memorization_rate")]
        L += [f"| {k} | {_fmt(v)} |" for k, v in g["latency"].items()]
        for s in g["samples"][:3]:
            L += ["", f"sample: `{s['repr'][:160]}`"]
    return "\n".join(L) + "\n"


def flatten(rep, prefix=""):
    out = {}
    for k, v in rep.items():
        if k in ("samples", "run", "which", "split", "data", "arch"):
            continue
        if isinstance(v, dict):
            out.update(flatten(v, f"{prefix}{k}."))
        elif v is None or (isinstance(v, (int, float)) and not isinstance(v, bool)):
            out[f"{prefix}{k}"] = v
    return out


def compare_markdown(reps):
    flat = {w: flatten(r) for w, r in reps.items()}
    names = list(flat)
    keys = [k for k in flat[names[0]] if all(k in f for f in flat.values())]
    L = ["| metric | " + " | ".join(names) + " |", "|---|" + "---|" * len(names)]
    return "\n".join(L + [f"| {k} | " + " | ".join(_fmt(flat[n][k]) for n in names) + " |" for k in keys]) + "\n"


def run_report(run_dir, split="val", which="ema", device=None, max_windows=None):
    import train
    device = device or ("cuda" if torch.cuda.is_available() else "cpu")
    model, cfg = train.load_model_from_run(run_dir, which=which, device=device)
    model.eval()
    name = cfg.train.data
    rep = {"run": os.path.basename(os.path.normpath(run_dir)), "arch": cfg.arch, "which": which, "split": split, "data": name,
           "training": training_stats(run_dir, model)}
    if cfg.arch == "diffusion":
        rep["diffusion"] = eval_diffusion(model, name, split, device, windows=max_windows or 64)
    else:
        rep["lm"] = eval_lm(model, name, split, device, max_windows=max_windows)
        rep["tasks"] = eval_tasks(model, name, device)
    rep["generation"] = eval_generation(model, name, device)
    base = os.path.join(run_dir, f"eval_{split}_{which}")
    with open(base + ".json", "w") as f:
        json.dump(rep, f, indent=1)
    with open(base + ".md", "w", encoding="utf-8") as f:
        f.write(to_markdown(rep))
    return rep


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", required=True)
    ap.add_argument("--split", default="val", choices=["val", "test"])
    ap.add_argument("--which", default="ema", choices=["raw", "ema", "both"])
    ap.add_argument("--max-windows", type=int, default=None)
    ap.add_argument("--device", default=None)
    a = ap.parse_args(argv)
    whichs = ["raw", "ema"] if a.which == "both" else [a.which]
    reps = {w: run_report(a.run, a.split, w, a.device, a.max_windows) for w in whichs}
    text = compare_markdown(reps) if len(reps) > 1 else to_markdown(reps[whichs[0]])
    print(text.encode("ascii", "replace").decode())


if __name__ == "__main__":
    main()
